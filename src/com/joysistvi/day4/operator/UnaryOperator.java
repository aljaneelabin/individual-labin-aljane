package com.joysistvi.day4.operator;

public class UnaryOperator {
    public static void main(String[] args) {
        // negating  an expression = number use a symbol (-)
        // note java read top to bottom
        int num = -10;
        System.out.println(-num);

        // inverting the value of a boolean use a symbol (!)
        boolean isActive = false;
        System.out.println(!isActive); // here to negate

        // increment - dagdag /decrement - bawas a value by one (+1 / -1) dalawang ++/--
        int num2 = 20;
        System.out.println(++num2); // - increment (you can use word number)
        System.out.println(--num2); // - decrement

        // post or pre increment
        // post increment r decrement
        int number = 20;
        System.out.println(number); // pwede ng diretso print
        // for looping - post increment

















    }
}
